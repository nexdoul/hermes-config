#!/bin/bash
# taskctl.sh — create / inspect / open / close tasks in the registry.
#
#   taskctl.sh create <id> --script <path> [--desc "..."] [--max-attempts N]
#   taskctl.sh list
#   taskctl.sh show  <id>
#   taskctl.sh stop   <id>     # mark done-ish: "a human said stop". blocks relaunch.
#   taskctl.sh resume <id>     # clear a stop and allow relaunch again
#   taskctl.sh reset  <id>     # clear attempts/state so a human can force a retry
#
# State vocabulary (per task, in /home/hatch/state/tasks/<id>/):
#   pending    registered, never completed, may be relaunched
#   running    a wrapper is alive working on it (recorded pgid)
#   done       payload exited 0 — NEVER relaunch (this is the 已完成 marker)
#   stopped    human asked it to stop — NEVER relaunch until resumed
#   exhausted  hit max attempts — NEVER relaunch until reset
set -u
TASKS_ROOT="${TASKS_ROOT:-/home/hatch/state/tasks}"
mkdir -p "$TASKS_ROOT"

bold() { printf '\033[1m%s\033[0m' "$*"; }
die() { echo "taskctl: $*" >&2; exit 1; }
usage() { sed -n '2,14p' "$0" >&2; exit 2; }

cmd="${1:-}"
[ -z "$cmd" ] && usage
shift || true

case "$cmd" in
create)
    id=""; script=""; desc=""; maxa="3"
    while [ $# -gt 0 ]; do
        case "$1" in
            --script) script="${2:-}"; shift 2 || true ;;
            --desc)   desc="${2:-}";   shift 2 || true ;;
            --max-attempts) maxa="${2:-3}"; shift 2 || true ;;
            -h|--help) usage ;;
            -*) die "unknown option $1" ;;
            *)  [ -z "$id" ] && id="$1" || die "unexpected arg $1"; shift ;;
        esac
    done
    [ -z "$id" ] && die "create needs <id>"
    [ -z "$script" ] && die "create needs --script <path>"
    [ -f "$script" ] || die "script not found: $script"
    case "$id" in *[!A-Za-z0-9._-]*) die "id must be [A-Za-z0-9._-], got '$id'" ;; esac
    d="$TASKS_ROOT/$id"
    if [ -d "$d" ]; then
        echo "taskctl: '$id' already exists" >&2
        exit 1
    fi
    mkdir -p "$d"
    # Absolute, so the watchdog can run it from any cwd.
    abs=$(cd "$(dirname "$script")" && pwd)/$(basename "$script")
    # run.sh is a SHIM that execs the original path, never a copy of it: the
    # agent keeps editing the original script, and every relaunch picks up the
    # new version. (Copying the content instead froze the payload at create
    # time and made `bash run.sh` fail with 126.)
    {
        echo '#!/bin/bash'
        echo "# generated by taskctl: do not edit, edit the payload instead"
        echo "exec bash \"$abs\""
    } >"$d/run.sh"
    printf '%s\n' "$abs" >"$d/payload_path"
    printf '%s\n' "$maxa" >"$d/max_attempts"
    printf '%s\n' "$(date +%s)" >"$d/created_at"
    [ -n "$desc" ] && printf '%s\n' "$desc" >"$d/desc"
    echo "pending" >"$d/state"
    echo "0" >"$d/attempts"
    echo "created task $id -> $abs (max_attempts=$maxa)"
    ;;
list)
    printf '%-24s %-10s %-6s %-8s %s\n' TASK STATE ATTEMPTS MAXDESC DESC
    for d in "$TASKS_ROOT"/*; do
        [ -d "$d" ] || continue
        id=$(basename "$d")
        st=$(cat "$d/state" 2>/dev/null || echo ?)
        att=$(cat "$d/attempts" 2>/dev/null || echo 0)
        ma=$(cat "$d/max_attempts" 2>/dev/null || echo 3)
        ds=$(cat "$d/desc" 2>/dev/null || echo "")
        printf '%-24s %-10s %-6s %-8s %s\n' "$id" "$st" "$att" "$ma" "$ds"
    done
    ;;
show)
    id="${1:-}"; [ -z "$id" ] && usage
    d="$TASKS_ROOT/$id"; [ -d "$d" ] || die "no such task '$id'"
    for f in desc run.sh max_attempts state attempts started_at completed_at exhausted_at stopped_at reply pgid wrapper_pid; do
        [ -f "$d/$f" ] && printf '%-14s %s\n' "$f:" "$(cat "$d/$f")"
    done
    ;;
stop)
    id="${1:-}"; [ -z "$id" ] && usage
    d="$TASKS_ROOT/$id"; [ -d "$d" ] || die "no such task '$id'"
    echo "stopped" >"$d/state.tmp" && mv -f "$d/state.tmp" "$d/state"
    date +%s >"$d/stopped_at.tmp" && mv -f "$d/stopped_at.tmp" "$d/stopped_at"
    # Also kill the wrapper tree if it is running right now: a stop that only
    # flips a flag would let a live task keep working while claiming to be
    # stopped. The watchdog then sees state=stopped and leaves it alone.
    p=$(cat "$d/pgid" 2>/dev/null || echo "")
    killed=""
    if [ -n "$p" ] && kill -0 "$p" 2>/dev/null; then
        kill -TERM -- -"$p" 2>/dev/null && killed=", killed live pgid $p"
    fi
    echo "task $id stopped (will not be relaunched$killed)"
    ;;
resume)
    id="${1:-}"; [ -z "$id" ] && usage
    d="$TASKS_ROOT/$id"; [ -d "$d" ] || die "no such task '$id'"
    st=$(cat "$d/state" 2>/dev/null || echo pending)
    case "$st" in
        stopped|exhausted|pending) ;;
        done) die "'$id' is done — create a new task instead of resuming a finished one" ;;
        *) die "'$id' is $st" ;;
    esac
    echo "pending" >"$d/state.tmp" && mv -f "$d/state.tmp" "$d/state"
    rm -f "$d/stopped_at" "$d/exhausted_at" 2>/dev/null || true
    echo "0" >"$d/attempts.tmp" && mv -f "$d/attempts.tmp" "$d/attempts"
    echo "task $id resumed (attempts reset); the watchdog will relaunch it"
    ;;
reset)
    id="${1:-}"; [ -z "$id" ] && usage
    d="$TASKS_ROOT/$id"; [ -d "$d" ] || die "no such task '$id'"
    st=$(cat "$d/state" 2>/dev/null || echo pending)
    echo "pending" >"$d/state.tmp" && mv -f "$d/state.tmp" "$d/state"
    echo "0" >"$d/attempts.tmp" && mv -f "$d/attempts.tmp" "$d/attempts"
    rm -f "$d/completed_at" "$d/exhausted_at" "$d/stopped_at" 2>/dev/null || true
    echo "task $id reset to pending from state=$st (attempts cleared)"
    ;;
*) usage ;;
esac
